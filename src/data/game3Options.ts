/**
 * Returns a randomized subset of options for Game 3 so every session looks fresh!
 */
export function getGame3SessionOptions() {
  return {
    characters: pickRandomSubset(ALL_CHARACTERS, 6),
    locations: pickRandomSubset(ALL_LOCATIONS, 6),
    actions: pickRandomSubset(ALL_ACTIONS, 6),
    styles: pickRandomSubset(ALL_STYLES, 4),
    details: pickRandomSubset(ALL_DETAILS, 6),
  };
}

function pickRandomSubset<T>(arr: T[], count: number): T[] {
  const shuffled = [...arr].sort(() => 0.5 - Math.random());
  return shuffled.slice(0, count);
}

