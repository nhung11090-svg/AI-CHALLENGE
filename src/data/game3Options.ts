export function buildPromptFromSelection(selection: Partial<import('../types').PromptSelection>): { vietnamesePrompt: string; englishPrompt: string } {
  const charLabel = selection.character?.label || 'Nhân vật AI';
  const charEng = selection.character?.englishLabel || 'a friendly cute character';
  
  const locLabel = selection.location?.label || 'Không gian vòm';
  const locEng = selection.location?.englishLabel || 'in a magical space';

  const actLabel = selection.action?.label || 'Hành động';
  const actEng = selection.action?.englishLabel || 'doing an exciting activity';

  const styleLabel = selection.style?.label || '3D Pixar';
  const styleEng = selection.style?.englishLabel || '3D Pixar animation style';

  const detailsLabels = selection.details?.map((d) => d.label).join(', ');
  const detailsEng = selection.details?.map((d) => d.englishLabel).join(', ');

  const vietnamesePrompt = `${charLabel} đang ${actLabel} tại ${locLabel}. Phong cách: ${styleLabel}${detailsLabels ? `. Chi tiết: ${detailsLabels}` : ''}.`;
  
  const englishPrompt = `${charEng}, ${actEng}, ${locEng}${detailsEng ? `, ${detailsEng}` : ''}, ${styleEng}, high quality, school appropriate, bright vibrant masterpiece.`;

  return { vietnamesePrompt, englishPrompt };
}

